use dioxus::prelude::*;

/// Declares every demo module and `sections()`, the page's sections in order, from one list.
macro_rules! gallery {
    ($($module:ident $title:literal $demo:ident,)*) => {
        $(mod $module;)*

        fn sections() -> Element {
            rsx! { $(section { h2 { $title } $module::$demo {} })* }
        }
    };
}

